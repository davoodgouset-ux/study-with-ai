@app.post("/users", response_model=UserResponse, status_code=201, tags=["Users (MySQL Database)"])
def create_user(user_data: UserCreate, db: Session = Depends(get_db)):
    """
    Creates a new user and saves them permanently into the MySQL database.
    
    Parameters:
        user_data (UserCreate): The incoming JSON request body validated by Pydantic.
        db (Session): Database session injected by FastAPI using Depends(get_db).
        
    Returns:
        UserResponse: The newly created user object (excluding the password).
    """
    # Step 1: Check if a user with the same email already exists in MySQL
    # In SQL: SELECT * FROM users WHERE email = :email LIMIT 1;
    existing_user = db.query(User).filter(User.email == user_data.email).first()
    if existing_user:
        raise HTTPException(
            status_code=400,
            detail=f"Registration failed: Email '{user_data.email}' is already registered."
        )

    # Step 2: Create a new SQLAlchemy User model instance
    new_user = User(
        name=user_data.name,
        email=user_data.email,
        password=user_data.password  # In Phase 5 we will hash this with bcrypt
    )

    # Step 3: Add the object to the database session transaction
    db.add(new_user)

    # Step 4: Commit the transaction to permanently write the row into MySQL on disk
    db.commit()

    # Step 5: Refresh the object to retrieve values generated by MySQL (such as the auto-increment ID)
    db.refresh(new_user)

    return new_user


@app.get("/users", response_model=list[UserResponse], tags=["Users (MySQL Database)"])
def get_all_users(db: Session = Depends(get_db)):
    """
    Retrieves all users permanently stored in MySQL.
    
    In SQL: SELECT * FROM users;
    """
    users = db.query(User).all()
    return users


@app.get("/users/{user_id}", response_model=UserResponse, tags=["Users (MySQL Database)"])
def get_user_by_id(user_id: int, db: Session = Depends(get_db)):
    """
    Retrieves a single user by their primary key ID from MySQL.
    
    In SQL: SELECT * FROM users WHERE id = :user_id LIMIT 1;
    """
    user = db.query(User).filter(User.id == user_id).first()
    if not user:
        raise HTTPException(
            status_code=404,
            detail=f"User with ID {user_id} was not found in database"
        )
    return user


@app.delete("/users/{user_id}", tags=["Users (MySQL Database)"])
def delete_user(user_id: int, db: Session = Depends(get_db)):
    """
    Deletes a user permanently from MySQL.
    
    In SQL: DELETE FROM users WHERE id = :user_id;
    """
    user = db.query(User).filter(User.id == user_id).first()
    if not user:
        raise HTTPException(
            status_code=404,
            detail=f"Cannot delete: User with ID {user_id} does not exist"
        )

    # Delete row and commit
    db.delete(user)
    db.commit()

    return {
        "status": "success",
        "message": f"User '{user.name}' (ID {user_id}) was permanently deleted from MySQL."
    }
