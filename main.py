# Step 1: Create all database tables in MySQL on startup
# If tables do not exist, SQLAlchemy will automatically issue the
# CREATE TABLE queries to MySQL.
Base.metadata.create_all(bind=engine)

# Step 2: Initialize FastAPI application instance
